/**
 * Экранирование пользовательского ввода для Prisma `contains`/`startsWith`/
 * `endsWith`.
 *
 * ЗАЧЕМ. Prisma параметризует ЗНАЧЕНИЕ (классической SQL-инъекции нет), но сам
 * шаблон собирает как `LIKE '%' || $1 || '%'`, и спецсимволы LIKE внутри
 * значения остаются рабочими:
 *
 *   поиск «%»  ->  LIKE '%%%'   -> совпадает с КАЖДОЙ непустой строкой
 *   поиск «_»  ->  LIKE '%_%'   -> совпадает с КАЖДОЙ непустой строкой
 *
 * То есть один процент, случайно вставленный в строку поиска, превращал список
 * студентов в выгрузку всей базы — 10 000 строк вместо ожидаемого «ничего не
 * найдено». Это не гипотетика: процент попадает в поле при копипасте суммы
 * («50%»), а подчёркивание — при вставке идентификатора.
 *
 * Отдельно неприятно, что отказ выглядит как успех: ошибки нет, страница
 * отрисовывается, просто показывает не то. Заметить это в UI почти невозможно.
 *
 * КАК. В PostgreSQL символ экранирования LIKE по умолчанию — обратная косая
 * черта, отдельный ESCAPE в запросе не нужен. Экранируем сам бэкслеш ПЕРВЫМ:
 * иначе «\» превратился бы в «\\», а затем его же вторая замена испортила бы
 * уже экранированные проценты.
 */
export function escapeLike(value: string): string {
  return value.replace(/\\/g, '\\\\').replace(/%/g, '\\%').replace(/_/g, '\\_');
}

/**
 * Готовое условие Prisma для поиска подстроки без учёта регистра.
 *
 * Использовать ВЕЗДЕ вместо `{ contains: userInput, mode: 'insensitive' }`.
 * Прямой `contains` с пользовательским вводом — это тот самый баг с процентом.
 */
export function containsInsensitive(value: string): { contains: string; mode: 'insensitive' } {
  return { contains: escapeLike(value), mode: 'insensitive' };
}
