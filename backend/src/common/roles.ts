import { Role } from '@prisma/client';

/**
 * Иерархия ролей в CRM GrantChina:
 *  - FOUNDER  — верхний уровень («Основатель»). Видит и может редактировать
 *               всё в системе, включая единоличное управление сотрудниками
 *               (users.controller.ts — там роль FOUNDER проверяется отдельно,
 *               см. isFounder ниже).
 *  - ADMIN    — операционный уровень («Администратор»). Те же права на
 *               студентов/заявки/задачи/программы, что и у FOUNDER, но не
 *               может создавать/удалять сотрудников и менять им роли.
 *  - EMPLOYEE — «Менеджер» в интерфейсе. Видит и редактирует только то, что
 *               назначено лично ему (managerId/chinaManagerId/assignedToId),
 *               либо ещё никому не назначенные («свободные») записи.
 *
 * ВАЖНО: раньше по всему бэкенду проверка привилегий была захардкожена как
 * `user.role !== 'ADMIN'`. Поскольку FOUNDER по иерархии стоит ВЫШЕ ADMIN,
 * такая проверка ошибочно резала доступ Основателю. Все подобные проверки
 * должны использовать isPrivileged() ниже, а не сравнение с 'ADMIN' напрямую.
 */

/** true для FOUNDER и ADMIN — «привилегированные» роли, видят/редактируют всё. */
export function isPrivileged(role: Role | string | null | undefined): boolean {
  return role === 'FOUNDER' || role === 'ADMIN';
}

/**
 * true только для FOUNDER — используется там, где ADMIN намеренно
 * ограничен (например, управление сотрудниками в users.controller.ts,
 * где ADMIN имеет только read-only доступ).
 */
export function isFounder(role: Role | string | null | undefined): boolean {
  return role === 'FOUNDER';
}

/**
 * ТЗ v3 раздел 4 — «Администратор: только просмотр: видит финансовую аналитику
 * и платежи, но НЕ МОЖЕТ ничего изменять, добавлять или удалять в финансовой
 * части». Критерий приёмки №4.
 *
 * ЗАЧЕМ ОТДЕЛЬНАЯ ФУНКЦИЯ, А НЕ ПРАВКА isPrivileged():
 * isPrivileged() отвечает на вопрос «видит ли этот человек чужие записи» и
 * используется в ~50 местах — студенты, заявки, документы, консультации.
 * По тому же ТЗ Администратор ОБЯЗАН видеть всех студентов Таджикистана и
 * Китая, поэтому менять её семантику нельзя: это отрезало бы ему ровно то,
 * что ТЗ ему оставляет. Финансы — отдельная ось прав, и у неё отдельный
 * предикат.
 *
 * ЧТО СЧИТАЕТСЯ «ФИНАНСОВОЙ ЧАСТЬЮ»: платежи (Payment), график платежей
 * (PaymentSchedule), договоры с их суммами (Contract), зарплатная часть
 * (Payslip, BonusRule, EmployeeCompensation). Программы обучения (Program.cost)
 * НЕ входят: это каталог услуг, а не операция с деньгами, и ТЗ перечисляет
 * в финансовой части именно «аналитику и платежи».
 *
 * ВАЖНО про EMPLOYEE: менеджер платежи проводить МОЖЕТ («Просмотр и проведение
 * платежей только по своим студентам»), поэтому функция запрещает запись
 * ровно одной роли — ADMIN. Проверка построена как явный список разрешённых,
 * а не как `role !== 'ADMIN'`: при появлении новой роли она по умолчанию
 * окажется без доступа к деньгам, а не с ним.
 */
export function canWriteFinance(role: Role | string | null | undefined): boolean {
  return role === 'FOUNDER' || role === 'EMPLOYEE';
}

/**
 * ПЛАТЕЖИ — отдельная ось от остальной финансовой части (решение владельца
 * 12.08.2026): Администратору открыто ВНЕСЕНИЕ оплат по любому студенту —
 * создать, править свой черновик, приложить чеки, подать, отозвать. Прежний
 * строгий read-only Администратора из ТЗ v3 (критерий приёмки №4) в части
 * платежей снят владельцем сознательно.
 *
 * ЧТО НЕ ОТКРЫТО: одобрение/отклонение/аннулирование (@Roles(FOUNDER) в
 * payments.controller) и график платежей — контроль «вносит один, одобряет
 * другой» для Администратора сохраняется. Договоры и зарплатная часть живут
 * на canWriteFinance/canManageFinance и НЕ ослаблены: владелец просил именно
 * оплату, расширять заодно договоры — значит открыть Администратору сумму
 * договора, а на ней считается бонус менеджера.
 */
export function canWritePayments(role: Role | string | null | undefined): boolean {
  return role === 'FOUNDER' || role === 'ADMIN' || role === 'EMPLOYEE';
}

/**
 * Полное управление финансами — только Основатель (строка «Полное управление:
 * создание, проведение, редактирование и удаление платежей, управленческие
 * отчёты» в таблице ролей ТЗ v3).
 *
 * Отличие от canWriteFinance(): та отвечает «можно ли вообще трогать деньги»
 * (менеджеру — можно, но лишь по своим студентам), эта — «можно ли управлять
 * финансовым контуром целиком»: одобрять платежи, править график, подписывать
 * договоры, утверждать зарплатные листы и менять формулы бонусов.
 */
export function canManageFinance(role: Role | string | null | undefined): boolean {
  return role === 'FOUNDER';
}
