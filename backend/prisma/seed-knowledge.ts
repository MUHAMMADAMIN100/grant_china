async function main() {
  let created = 0;
  let updated = 0;

  for (const a of ARTICLES) {
    const existing = await prisma.knowledgeArticle.findFirst({
      where: { title: a.title, deletedAt: null },
      select: { id: true },
    });
    if (existing) {
      await prisma.knowledgeArticle.update({
        where: { id: existing.id },
        data: {
          category: a.category,
          body: a.body,
          tags: a.tags,
          sortOrder: a.sortOrder,
          published: true,
        },
      });
      updated += 1;
    } else {
      await prisma.knowledgeArticle.create({
        data: {
          title: a.title,
          category: a.category,
          body: a.body,
          tags: a.tags,
          sortOrder: a.sortOrder,
          published: true,
        },
      });
      created += 1;
    }
  }

  console.log(`База знаний: создано ${created}, обновлено ${updated} статей.`);
}

main()
  .catch((e) => {
    console.error('Не удалось наполнить базу знаний:', e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
